import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(here, "../../..")
const liveDir = path.join(repoRoot, "data/live")
const outputDir = path.join(here, "../src/generated")
const outputFile = path.join(outputDir, "live-corpus.ts")

const files = fs.existsSync(liveDir)
  ? fs.readdirSync(liveDir).filter((name) => name.endsWith(".json")).sort()
  : []

if (!files.length) {
  throw new Error("JIZZ web build requires at least one data/live/*.json bundle")
}

const bundles = files.map((name) => JSON.parse(fs.readFileSync(path.join(liveDir, name), "utf8")))
for (const bundle of bundles) {
  if (bundle.corpus_kind !== "LIVE_RESEARCH") {
    throw new Error(`${bundle.phenomenon?.id ?? "unknown"} is not LIVE_RESEARCH`)
  }
  if (!bundle.research_issue?.number) {
    throw new Error(`${bundle.phenomenon?.id ?? "unknown"} has no issue-first lineage`)
  }
}

fs.mkdirSync(outputDir, { recursive: true })
const source = [
  "/* generated by apps/web/scripts/generate-live-data.mjs */",
  "import type { LiveBundle } from \"../types\"",
  "",
  `export const liveBundles = ${JSON.stringify(bundles, null, 2)} as LiveBundle[]`,
  "",
].join("\n")

fs.writeFileSync(outputFile, source)
console.log(`Generated JIZZ web corpus: ${bundles.length} live phenomenon bundle(s).`)
